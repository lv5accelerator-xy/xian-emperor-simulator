"use strict";
const assert = require("node:assert/strict");
const { harness, plain, CORE_KEY } = require("./helpers/game-harness");
const run = harness(); run.mount("save-backups"); run.window.XianShortChallenges.start("xudu_mutiny"); run.flush();
const first = run.window.XianSaveBackups.getEntries()[0];
run.decide(1); run.api.endTurn(); run.flush();
const before = plain(run.api.getState()), stores = run.stores();
run.node("backups-btn").click();
assert.match(run.node("modal-body").innerHTML, /许都夜变[\s\S]*备份时间[\s\S]*存档 v/);
const exportButtons = run.node("modal-body").querySelectorAll("[data-backup-export]");
exportButtons.find(button => button.dataset.backupExport === "month-1").click(); run.flush();
assert.equal(run.downloads.length, 1);
assert.deepEqual(JSON.parse(run.downloads[0].text), first.bundle, "download must contain the selected checkpoint, not the current save");
assert.deepEqual(run.stores(), stores); assert.deepEqual(plain(run.api.getState()), before);
run.node("modal-body").querySelectorAll("[data-backup-restore]").find(button => button.dataset.backupRestore === "month-1").click();
assert.match(run.node("modal-body").innerHTML, /当前[\s\S]*恢复后/);
const difference = run.window.XianSaveBackups.compare(first.bundle, run.api.captureFullSave());
assert.equal(difference.differentGame, false); assert.equal(difference.saved.name, "许都夜变");
assert.equal(difference.rows.find(row => row.path === "turn").current, 2); assert.equal(difference.rows.find(row => row.path === "turn").saved, 1);
run.node("modal-cancel").click(); run.flush(); assert.deepEqual(run.stores(), stores); assert.deepEqual(plain(run.api.getState()), before);
run.window.XianShortChallenges.start("white_horse"); run.flush();
const other = run.window.XianSaveBackups.compare(first.bundle, run.api.captureFullSave());
assert.equal(other.differentGame, true); assert.notEqual(other.saved.name, other.current.name);
assert.equal(first.bundle.stores[CORE_KEY].turn, 1);
console.log("Backup identities, versions, restore differences, read-only cancel and selected full export passed.");
